namespace ProjectSeWoo.Shared;

/// <summary>
/// 세이브 파일의 단일 소유자 (기획확정-일감분배-260907.md §7-5). 갑 제공 → 을 소비.
///
/// <b>왜 <c>SaveIO</c> 를 직접 부르게 두지 않는가</b> — 세이브 파일에 쓰는 주체가
/// B5 부터 <b>둘</b>이 되기 때문이다. 셸은 창 위치·옵션(<c>settings</c>)을 쓰고,
/// 게임은 나무·재화·누적 타수를 쓴다. 양쪽이 각자 "읽고 → 자기 몫만 고치고 →
/// 통째로 쓰기" 를 하면 사이에 낀 상대의 변경이 조용히 사라진다. 드래그 한 번에
/// 바나나가 되돌아가는 종류의 버그이고, 재현이 타이밍에 달려 있어 잡기 어렵다.
///
/// 그래서 <b>이 세션에 <see cref="SaveData"/> 인스턴스는 하나뿐이다.</b> 셸도
/// 게임도 같은 객체를 고치고, 디스크에 언제 쓸지는 플랫폼이 혼자 정한다.
/// 읽기-수정-쓰기 경합이 구조적으로 생길 수 없다.
///
/// <b>디스크 쓰기는 묶인다.</b> <see cref="MarkDirty"/> 는 "바뀌었다" 고만 알리고
/// 실제 쓰기는 플랫폼이 간격을 두고 한다 - 상주 앱이라 타이핑하는 내내 살아 있고,
/// 매 변경마다 쓰면 유휴 부하 기준(§7-3)에 맞지 않는다.
/// </summary>
public interface ISaveStore
{
    /// <summary>
    /// 이 세션의 유일한 세이브 객체. <b>직접 고치면 된다</b> - 고친 뒤
    /// <see cref="MarkDirty"/> 를 부르는 것이 전부다.
    ///
    /// 별도 포맷을 만들지 않고 <see cref="SaveData"/> 를 그대로 쓰는 것은 A1 때
    /// 정한 것이다 (docs/A1-CONTRACTS.md, B-TRACK-START.md §4-4). 게임이 안 건드리는
    /// 필드(<c>settings</c>)와 셸이 안 건드리는 필드(<c>tree</c> 등)는 서로의 값을
    /// 그대로 들고 왕복한다.
    /// </summary>
    SaveData Data { get; }

    /// <summary>
    /// <see cref="Data"/> 를 고친 뒤 부른다. 여러 번 불러도 되고, 실제 쓰기가
    /// 언제 일어나는지는 알 필요가 없다.
    /// </summary>
    void MarkDirty();

    /// <summary>
    /// 지금 당장 쓴다. <b>종료 경로에서만 쓴다</b> - 평소에는
    /// <see cref="MarkDirty"/> 로 충분하고, 이걸 자주 부르면 묶어 쓰는 의미가 없다.
    /// 바뀐 것이 없으면 아무 일도 하지 않는다.
    /// </summary>
    void FlushNow();
}
