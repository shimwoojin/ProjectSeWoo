using System;

namespace ProjectSeWoo.Shared;

/// <summary>
/// 전역 타건 수 공급자 (기획확정-일감분배-260907.md §8-2). 갑 제공 → 을 소비.
///
/// **키 코드를 읽지 않는다.** 이 인터페이스에 키를 나타내는 타입이 아예 없는 것이
/// 그 설계의 첫 번째 증거다 (§7-2, §7-6). 구현체도 콜백에서 <c>vkCode</c> 를
/// 변수에 담지 않도록 작성한다 — "안 읽는다"를 코드 레벨에서 증명할 수 있어야
/// 스토어 문구가 거짓말이 아니게 된다.
///
/// 이건 기능이 아니라 신뢰 문제다. 스팀 리뷰에 "키로거 아니냐" 글 하나면
/// 프로젝트가 죽는다.
/// </summary>
public interface IInputSource
{
    /// <summary>
    /// 100ms 배치로 타건 수를 알린다. 초당 캡과 연타 감쇠를 적용한 **뒤의** 개수다 (§6).
    ///
    /// 매 타마다 이벤트를 쏘지 않는 이유는 상주 앱의 유휴 부하 때문이고,
    /// 배치 크기가 100ms 인 것은 펀치 연출이 끊겨 보이지 않는 상한이기 때문이다.
    /// </summary>
    event Action<int> OnKeystrokes;

    /// <summary>기동 이후 누적 타수. 레벨 환산과 랭킹의 원본 값 (§6).</summary>
    long TotalCount { get; }

    /// <summary>
    /// false 면 게임 레이어는 **시간 기반 폴백**으로 전환한다.
    ///
    /// 이 플래그가 있는 이유는 안티치트·백신이 전역 입력을 막는 환경이 실재하고,
    /// 그때 게임이 멈추는 게 아니라 성장 소스만 바뀌면 되기 때문이다.
    /// 나무는 원래 시간으로 자란다 (§2-2). 타이핑은 수확 트리거일 뿐이다.
    /// </summary>
    bool IsAvailable { get; }
}
